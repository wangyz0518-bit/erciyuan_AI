def p(text='', bold=False, style=None):
    par = doc.add_paragraph(style=style)
    par.add_run(text).bold = bold
    return par

def h(text, level=2):
    return doc.add_heading(text, level)

def page(title):
    par = h(title, 1)
    par.paragraph_format.page_break_before = True

def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for col, width in zip(t.columns, widths):
        col.width = Cm(width)
    border = OxmlElement('w:tblBorders')
    for edge in ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']:
        el = OxmlElement('w:' + edge)
        for attr, value in [('val', 'single'), ('sz', '4'), ('color', 'D9D9D9')]:
            el.set(qn('w:' + attr), value)
        border.append(el)
    t._tbl.tblPr.append(border)
    for ri, values in enumerate([headers] + rows):
        cells = t.rows[0].cells if ri == 0 else t.add_row().cells
        no_split = OxmlElement('w:cantSplit')
        cells[0]._tc.getparent().get_or_add_trPr().append(no_split)
        for ci, (cell, value, width) in enumerate(zip(cells, values, widths)):
            cell.width = Cm(width)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            props = cell._tc.get_or_add_tcPr()
            cell_borders = OxmlElement('w:tcBorders')
            for edge in ['top', 'left', 'bottom', 'right']:
                el = OxmlElement('w:' + edge)
                for attr, border_value in [('val', 'single'), ('sz', '4'), ('color', 'D9D9D9')]:
                    el.set(qn('w:' + attr), border_value)
                cell_borders.append(el)
            props.append(cell_borders)
            mar = OxmlElement('w:tcMar')
            for edge, size in [('top', '85'), ('bottom', '85'), ('left', '105'), ('right', '105')]:
                el = OxmlElement('w:' + edge)
                el.set(qn('w:w'), size)
                el.set(qn('w:type'), 'dxa')
                mar.append(el)
            props.append(mar)
            fill = OxmlElement('w:shd')
            fill.set(qn('w:fill'), 'E6EDF3' if ri == 0 else 'FFFFFF')
            props.append(fill)
            par = cell.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            par.paragraph_format.line_spacing = Pt(14.5)
            if ci == 0:
                par.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = par.add_run(str(value))
            run.font.size = Pt(10)
            run.bold = ri == 0
    spacer = p()
    spacer.paragraph_format.space_after = Pt(2)
    spacer.paragraph_format.line_spacing = Pt(2)
    for run in spacer.runs:
        run.font.size = Pt(1)
    return t

